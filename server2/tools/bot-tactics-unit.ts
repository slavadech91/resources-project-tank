// Offline geometry and decision checks. No accounts, sockets or database.
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { chooseBotTask,type TacticalContext } from '../src/battle/botTactics.ts';
import { BotWorld,type BotParticipant } from '../src/battle/botWorld.ts';
import { GarageCatalog } from '../src/garage/catalog.ts';
import { loadBotProfile } from '../src/battle/botProfile.ts';
import type { MapData } from '../src/battle/mapData.ts';
const context:TacticalContext={hp:1,visible:false,range:4000,memory:false,danger:false,afraid:false,justFired:false,cover:false,medical:false,supply:false,drop:false,canFire:true};
const choose=(values:Partial<TacticalContext>,r=0)=>chooseBotTask({...context,...values},()=>r);
assert.equal(choose({visible:true}),'snipe');
assert.equal(choose({visible:true},0.9),'attackMove');
assert.equal(choose({},0.9),'patrol');assert.equal(choose({}),'patrol');
assert.equal(choose({hp:0.2,visible:true}),'retreat');
assert.equal(choose({afraid:true}),'retreat');
assert.equal(choose({visible:true,danger:true}),'evade');
assert.equal(choose({justFired:true,memory:true,cover:true}),'reloadCover');
assert.equal(choose({memory:true},0.9),'investigate');
assert.equal(choose({hp:0.5,medical:true,supply:true}),'supply');
assert.equal(choose({supply:true}),'supply');assert.equal(choose({drop:true}),'drop');
const configDir=resolve('dev/configs'),{profile,loadout}=loadBotProfile(configDir,new GarageCatalog(configDir));
const box=(x:number,y:number,z:number,sx:number,sy:number,sz:number)=>`<collision-box><size><x>${sx}</x><y>${sy}</y><z>${sz}</z></size><position><x>${x}</x><y>${y}</y><z>${z}</z></position><rotation><x>0</x><y>0</y><z>0</z></rotation></collision-box>`;
const spawn={position:{x:0,y:-1000,z:130},orientation:{x:0,y:0,z:0}};
const map:MapData={mapId:1,key:'fixture',xml:box(0,0,-50,8000,8000,100),spawns:{dm:[spawn],red:[spawn],blue:[spawn]},killZones:[],bonusRegions:[]};
const actor:BotParticipant={id:1,team:2,state:'active',life:1,health:loadout.maxHealth,position:spawn.position,orientation:spawn.orientation,sample:null,loadout,speedFactor:1};
const enemy:BotParticipant={...actor,id:2,position:{x:0,y:2200,z:700}};
let picked=0,shots=0;
const world=new BotWorld(map,profile,(_id,s)=>{actor.position={x:s.px,y:s.py,z:s.pz};actor.sample=s;},()=>shots++,()=>0.4,()=>picked++);
world.spawn(1,1,spawn);
const internal=world as any,b=internal.bots.get(1);b.decisionAt=60000;
for(let i=0;i<60;i++)world.step([actor],i*33,i*33);
assert.ok(internal.perceive(b,enemy),'elevated enemy is perceived independently of firing sector');
assert.equal(internal.canAim(b,{x:0,y:200,z:3000},loadout),false,'vertical perception does not grant impossible auto-aim');
internal.assignTask(b,'snipe',actor.position,enemy,null,2200);
for(let i=0;i<30;i++)world.step([actor,enemy],2200+i*33,2200+i*33);
assert.equal(b.control,0,'distant snipe uses turret without steering hull');
b.memory={id:enemy.id,position:enemy.position,aim:enemy.position,seenAt:0};b.task='watch';b.taskUntil=30000;b.decisionAt=0;
world.step([actor],16000,16000);assert.equal(b.memory,null,'unseen enemy memory expires');
const position={x:actor.position!.x,y:actor.position!.y,z:700};
world.step([actor],17000,17000,{bonuses:[{bonusId:7,kind:'med',position,ageMs:0}],fallSpeed:300});
assert.equal(picked,0,'falling supply is not taken early');
world.step([actor],18000,18000,{bonuses:[{bonusId:7,kind:'med',position,ageMs:5000}],fallSpeed:300});
assert.equal(picked,1,'landed supply in contact is picked up');
world.step([actor],19000,19000,{bonuses:[{bonusId:8,kind:'gold',position,ageMs:5000}],fallSpeed:300});
assert.equal(picked,2,'bots can take a landed Gold Box');
assert.equal(world.navigation.findDrop(actor.position!,()=>0.5).length,0,'flat floor does not create an imaginary drop');
world.clear();
const wallMap={...map,xml:map.xml+box(0,400,350,1500,200,700)};
const covered=new BotWorld(wallMap,profile,()=>{},()=>{},()=>0.4);covered.spawn(1,1,spawn);
for(let i=0;i<100;i++)covered.navigation.expand();
const ci=covered as any,cb=ci.bots.get(1);
assert.equal(ci.perceive(cb,{...enemy,position:{x:0,y:2200,z:130}}),null,'wall blocks all tested target points');
assert.ok(ci.findCover({x:1600,y:-1000,z:130},{x:0,y:2200,z:200}),'cover search finds reachable hidden ground');
cb.cover=ci.findCover({x:1600,y:-1000,z:130},{x:0,y:2200,z:200});cb.memory={id:2,position:enemy.position,aim:enemy.position,seenAt:1000};
ci.assignTask(cb,'reloadCover',spawn.position,enemy,null,1000);cb.path=[];cb.nextShot=0;cb.taskUntil=30000;
ci.think(1,cb,{...actor,position:spawn.position},[{...actor,position:spawn.position}],2000);assert.equal(cb.task,'peek','after reloading in cover the bot peeks toward remembered position');
covered.clear();
const upperSpawn={position:{x:-500,y:0,z:630},orientation:{x:0,y:0,z:-Math.PI/2}};
const dropMap={...map,xml:map.xml+box(-2000,0,450,4000,6000,100),spawns:{dm:[upperSpawn,spawn],red:[upperSpawn],blue:[spawn]}};
let seed=14321;const random=()=>((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/2**32);
const fallingActor={...actor,position:upperSpawn.position,orientation:upperSpawn.orientation,sample:null};
const descent=new BotWorld(dropMap,profile,(_id,s)=>{fallingActor.position={x:s.px,y:s.py,z:s.pz};},()=>{},random);
descent.spawn(1,1,upperSpawn);for(let i=0;i<100;i++)descent.navigation.expand();
let route:ReturnType<typeof descent.navigation.findDrop>=[];
for(let i=0;i<20&&!route.length;i++)route=descent.navigation.findDrop(upperSpawn.position,random);
assert.ok(route.length,'broad lower platform permits a checked one-way descent');
const di=descent as any,db=di.bots.get(1);di.assignTask(db,'drop',upperSpawn.position,null,null,0,route);db.decisionAt=20000;
for(let frame=0;frame<220;frame++)descent.step([fallingActor],frame*33,frame*33);
assert.ok(fallingActor.position.z<200&&fallingActor.position.z>0,JSON.stringify({position:fallingActor.position,task:db.task,path:db.path.length,drop:!!db.drop,control:db.control}));
descent.clear();
const ramp=box(0,0,400,2500,1800,100).replace('<y>0</y><z>0</z></rotation>','<y>-0.3</y><z>0</z></rotation>');
const rampSpawn={position:{x:-1000,y:0,z:290},orientation:{x:0,y:0,z:-Math.PI/2}};
const rampMap={...map,xml:map.xml+ramp,spawns:{dm:[rampSpawn],red:[rampSpawn],blue:[rampSpawn]}};
const rampActor={...actor,position:rampSpawn.position,orientation:rampSpawn.orientation,sample:null};
const slope=new BotWorld(rampMap,profile,(_id,s)=>{rampActor.position={x:s.px,y:s.py,z:s.pz};},()=>{},random);
slope.spawn(1,1,rampSpawn);for(let i=0;i<200;i++)slope.navigation.expand();
const upper=slope.navigation.reachable(rampSpawn.position).find(n=>n.x>=1000&&n.z>700&&Math.abs(n.y)<300);
assert.ok(upper,'a continuous incline remains connected despite >100cm height changes per cell');
assert.ok(slope.navigation.canDrive(rampSpawn.position,upper),'ground guard follows the slope instead of requiring a flat braking corridor');
const si=slope as any,sb=si.bots.get(1);sb.path=slope.navigation.smooth(rampSpawn.position,slope.navigation.route(rampSpawn.position,upper));sb.task='patrol';sb.decisionAt=60000;
for(let frame=0;frame<600;frame++)slope.step([rampActor],frame*33,frame*33);
assert.ok(rampActor.position.x>600&&rampActor.position.z>650,'bot physically drives uphill on its suspension');
slope.clear();
const idleSpawn={position:{x:0,y:0,z:130},orientation:{x:0,y:0,z:0}};
const pushed={...actor,position:idleSpawn.position,sample:null};
const pusher:BotParticipant={...actor,id:9,position:{x:0,y:-800,z:89.25},sample:null};
let highest=0;
const contactWorld=new BotWorld(map,profile,(_id,s)=>{pushed.position={x:s.px,y:s.py,z:s.pz};highest=Math.max(highest,s.pz);},()=>{},random);
contactWorld.spawn(1,1,idleSpawn);const contactBot=(contactWorld as any).bots.get(1);contactBot.decisionAt=60000;
for(let frame=0;frame<100;frame++){
  pusher.position={x:0,y:-800+frame*12,z:89.25};
  pusher.sample={seq:frame,sampleTime:frame*33,life:1,chassis:1,turretControl:0,turretAngle:0,px:0,py:pusher.position.y,pz:89.25,qx:0,qy:0,qz:0,qw:1,vx:0,vy:12/.033,vz:0,ax:0,ay:0,az:0};
  contactWorld.step([pushed,pusher],frame*33,frame*33);
}
assert.ok(pushed.position.y>300,'server human proxy transfers sustained push into bot movement');
assert.ok(highest<180,'aligned tank contact does not launch the bot upward');
contactWorld.clear();
console.log('Bot tactics: task choices, stationary turret aim, vertical perception, memory, cover/peek and landed supplies OK', {shots});
