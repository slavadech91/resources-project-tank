// Offline deterministic probability/occlusion checks; no account or network activity.
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { GarageCatalog } from '../src/garage/catalog.ts';
import { loadBotProfile } from '../src/battle/botProfile.ts';
import { BotWorld,type BotParticipant } from '../src/battle/botWorld.ts';
import type { MapData } from '../src/battle/mapData.ts';
const configDir=resolve('dev/configs'),{profile,loadout}=loadBotProfile(configDir,new GarageCatalog(configDir));
const box=(x:number,y:number,z:number,sx:number,sy:number,sz:number)=>`<collision-box><size><x>${sx}</x><y>${sy}</y><z>${sz}</z></size><position><x>${x}</x><y>${y}</y><z>${z}</z></position><rotation><x>0</x><y>0</y><z>0</z></rotation></collision-box>`;
const spawn={position:{x:0,y:-1000,z:130},orientation:{x:0,y:0,z:0}};
const map:MapData={mapId:1,key:'reaction-fixture',xml:box(0,0,-50,6000,6000,100)+box(0,400,400,1400,100,800),spawns:{dm:[spawn],red:[spawn],blue:[spawn]},killZones:[],bonusRegions:[]};
const self:BotParticipant={id:1,team:2,state:'active',life:1,health:loadout.maxHealth-5,position:spawn.position,orientation:spawn.orientation,sample:null,loadout,speedFactor:1};
const shooter:BotParticipant={...self,id:2,health:loadout.maxHealth,position:{x:0,y:1500,z:90}};
const bystander:BotParticipant={...self,id:3,health:loadout.maxHealth,position:{x:-1400,y:-900,z:90}};
let roll=0.749999,shots=0;
const world=new BotWorld(map,profile,(_id,s)=>{self.position={x:s.px,y:s.py,z:s.pz};},()=>shots++,()=>roll);
world.spawn(1,1,spawn);for(let i=0;i<100;i++)world.navigation.expand();
const b=(world as any).bots.get(1);
assert.equal(world.hitBy(1,shooter,1000),true,'roll strictly below 0.75 recognizes attacker');
assert.equal(b.memory.id,2);assert.equal(b.hitFocus.until,13000);
shooter.position={x:100,y:1600,z:90};
assert.deepEqual(b.memory.position,{x:0,y:1500,z:90},'hidden attacker motion does not update stored location');
world.step([self,shooter,bystander],1000,1000);
assert.equal(b.task,'investigate','healthy hit bot searches even when its ordinary hurt reaction suggests fear');
assert.equal(b.memory.id,2,'another visible enemy does not erase hit-attacker priority');
assert.ok(b.path.length>0,'search uses a reachable route toward remembered location');
assert.equal(shots,0,'remembering a position does not permit shooting through a wall');
roll=0.75;
assert.equal(world.hitBy(1,bystander,1100),false,'roll equal to 0.75 belongs to the 25 percent failure interval');
assert.equal(b.memory.id,2,'failed reaction does not replace previous knowledge');
assert.equal(world.hitBy(1,self,1100),false,'self damage is not an enemy target');
world.step([self,shooter],14000,14000);
assert.equal(b.hitFocus,null,'damage priority expires instead of tracking forever');
world.spawn(1,2,spawn);assert.equal((world as any).bots.get(1).hitFocus,null,'new life clears damage knowledge');
world.clear();
console.log('Bot damage reaction: exact 75% boundary, attacker priority, copied position, search route, occlusion, expiry and respawn OK');
